# --- E2E: write_soul で書いた SOUL.md が公式 4 要素を満たす --------------


def test_written_soul_md_has_official_four_sections(tmp_path: Path) -> None:
    """Hermes One 公式仕様 (hermesagents.cc) の 4 要素を含む。"""
    out = tmp_path / "SOUL.md"
    write_soul(
        out,
        ["personality/tsundere", "speech/keigo"],
        weight="moderate",
        overwrite=True,
    )
    text = out.read_text(encoding="utf-8")
    for header in (
        "## 1. Name (エージェント名)",
        "## 2. Personality (性格特性)",
        "## 3. Tone (口調)",
        "## 4. Behavioral Guidelines (行動指針)",
    ):
        assert header in text, f"missing official section: {header}"


